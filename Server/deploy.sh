#!/usr/bin/env bash
# Deploys Server/leaderboard to the home server and syncs the game's leaderboard key.
#
#   Server/deploy.sh            deploy / update
#   Server/deploy.sh --logs     deploy, then follow the container log
#
# One-time server setup (see Server/leaderboard/README.md): SSH key login, and
#   sudo usermod -aG docker chris     (then log out/in)
set -euo pipefail

HOST="${CYCLOPEAN_HOST:-scaramanga.local}"
REMOTE_DIR="${CYCLOPEAN_REMOTE_DIR:-cyclopean}"            # relative to the remote home dir
PUBLIC_URL="${CYCLOPEAN_URL:-https://cyclopean.christrewartha.com}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/Server/leaderboard"
SECRETS_H="$ROOT/Source/Cyclops/Private/LeaderboardSecrets.h"

say() { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

say "Checking $HOST"
ssh -o BatchMode=yes -o ConnectTimeout=10 "$HOST" true || die "can't SSH to $HOST (key login set up?)"
ssh "$HOST" 'docker info >/dev/null 2>&1' \
  || die "user can't run docker on $HOST. One-time fix on the server:  sudo usermod -aG docker \$USER  then log out and back in."

say "Copying service files"
# Never ship local .env / data; the server keeps its own.
tar -C "$SRC" --exclude=.env --exclude=data --exclude=__pycache__ -czf - . \
  | ssh "$HOST" "mkdir -p '$REMOTE_DIR' && tar -xzf - -C '$REMOTE_DIR'"

say "Ensuring server secret"
ssh "$HOST" "cd '$REMOTE_DIR' && if [ ! -f .env ]; then
    umask 077
    printf 'LEADERBOARD_SECRET=%s\n' \"\$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')\" > .env
    echo '    created new .env'
  fi"

say "Building and starting container"
ssh "$HOST" "cd '$REMOTE_DIR' && docker compose up -d --build --remove-orphans" 

say "Waiting for health"
for i in $(seq 1 20); do
  if ssh "$HOST" "cd '$REMOTE_DIR' && docker compose exec -T leaderboard python -c \"import urllib.request;urllib.request.urlopen('http://localhost:8797/healthz')\"" 2>/dev/null; then
    ok=1; break
  fi
  sleep 1
done
[ "${ok:-}" = 1 ] || { ssh "$HOST" "cd '$REMOTE_DIR' && docker compose logs --tail 40 leaderboard"; die "service not healthy"; }

say "Syncing game key -> $(basename "$SECRETS_H")"
KEY="$(ssh "$HOST" "grep '^LEADERBOARD_SECRET=' '$REMOTE_DIR/.env' | cut -d= -f2-")"
[ -n "$KEY" ] || die "couldn't read LEADERBOARD_SECRET from server .env"
NEW_H="$(cat <<H
// Generated by Server/deploy.sh - git-ignored, do not commit.
#pragma once
#define CYCLOPS_LEADERBOARD_URL TEXT("$PUBLIC_URL")
#define CYCLOPS_LEADERBOARD_KEY "$KEY"
H
)"
if [ -f "$SECRETS_H" ] && [ "$(cat "$SECRETS_H")" = "$NEW_H" ]; then
  echo "    unchanged"
else
  printf '%s\n' "$NEW_H" > "$SECRETS_H"
  echo "    updated - rebuild the game to pick it up"
fi
unset KEY NEW_H

say "Checking $PUBLIC_URL"
code="$(curl -s -m 10 -o /dev/null -w '%{http_code}' "$PUBLIC_URL/healthz" || true)"
if [ "$code" = 200 ]; then
  echo "    public endpoint OK"
else
  echo "    public endpoint returned '$code' (DNS/tunnel may still be propagating; local service is healthy)"
fi

say "Done"
if [ "${1:-}" = "--logs" ]; then
  ssh -t "$HOST" "cd '$REMOTE_DIR' && docker compose logs -f leaderboard"
fi
